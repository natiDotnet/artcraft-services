use serde::{Deserialize, Serialize};

/// A single message in a conversation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatMessage {
  pub role: String,
  pub content: String,
  #[serde(skip_serializing_if = "Option::is_none")]
  pub name: Option<String>,
  #[serde(skip_serializing_if = "Option::is_none")]
  pub tool_call_id: Option<String>,
  #[serde(skip_serializing_if = "Option::is_none")]
  pub tool_calls: Option<Vec<ToolCall>>,
}

impl ChatMessage {
  pub fn system(content: impl Into<String>) -> Self {
    Self {
      role: "system".to_string(),
      content: content.into(),
      name: None,
      tool_call_id: None,
      tool_calls: None,
    }
  }

  pub fn user(content: impl Into<String>) -> Self {
    Self {
      role: "user".to_string(),
      content: content.into(),
      name: None,
      tool_call_id: None,
      tool_calls: None,
    }
  }

  pub fn assistant(content: impl Into<String>) -> Self {
    Self {
      role: "assistant".to_string(),
      content: content.into(),
      name: None,
      tool_call_id: None,
      tool_calls: None,
    }
  }
}

/// Request body for OpenRouter chat completions.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatCompletionRequest {
  pub model: String,
  pub messages: Vec<ChatMessage>,
  #[serde(default)]
  pub stream: bool,
  #[serde(skip_serializing_if = "Option::is_none")]
  pub temperature: Option<f32>,
  #[serde(skip_serializing_if = "Option::is_none")]
  pub max_tokens: Option<u32>,
  #[serde(skip_serializing_if = "Option::is_none")]
  pub tools: Option<Vec<ToolDefinition>>,
}

/// Tool definition conforming to OpenAI/OpenRouter standard.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolDefinition {
  pub r#type: String,
  pub function: FunctionDefinition,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionDefinition {
  pub name: String,
  pub description: String,
  pub parameters: serde_json::Value,
}

/// A tool invocation generated by the assistant.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolCall {
  pub id: String,
  pub r#type: String,
  pub function: FunctionCall,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionCall {
  pub name: String,
  pub arguments: String,
}

/// Non-streaming response.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatCompletionResponse {
  pub id: Option<String>,
  pub model: Option<String>,
  pub choices: Vec<ChatChoice>,
  pub usage: Option<ChatUsage>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatChoice {
  pub index: Option<u32>,
  pub message: ChatMessage,
  pub finish_reason: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatUsage {
  pub prompt_tokens: Option<u64>,
  pub completion_tokens: Option<u64>,
  pub total_tokens: Option<u64>,
}

/// A single streaming chunk emitted over Server-Sent Events (SSE).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatCompletionChunk {
  pub id: Option<String>,
  pub model: Option<String>,
  pub choices: Vec<ChatChunkChoice>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatChunkChoice {
  pub index: Option<u32>,
  pub delta: ChatChunkDelta,
  pub finish_reason: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatChunkDelta {
  pub role: Option<String>,
  pub content: Option<String>,
  pub tool_calls: Option<Vec<ToolCallDelta>>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolCallDelta {
  pub index: Option<u32>,
  pub id: Option<String>,
  pub r#type: Option<String>,
  pub function: Option<FunctionCallDelta>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionCallDelta {
  pub name: Option<String>,
  pub arguments: Option<String>,
}
